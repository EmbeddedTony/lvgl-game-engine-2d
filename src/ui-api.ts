export function uiIds(p: Project) {
  const used = new Map<string, string>();
  const define = (prefix: string, id: string) => {
    const trimmed =
      prefix === 'UI_SEQUENCE_'
        ? id.replace(/^sequence_/, '')
        : prefix === 'UI_STEP_'
          ? id.replace(/^step_/, '')
          : prefix === 'UI_PREFAB_'
            ? id.replace(/^(scene|prefab)_/, '')
            : id.replace(/^(scene|cue|node)_/, '');
    let base = prefix + trimmed.toUpperCase().replace(/[^A-Z0-9_]/g, '_'),
      name = base,
      index = 2;
    if (used.get(name) === id) return '';
    while (used.has(name)) name = base + '_' + index++;
    used.set(name, id);
    return `#define ${name} "${id}"`;
  };
  const groups: [string, string[]][] = [
    ['UI_SCENE_', p.scenes.map((s) => s.id)],
    ['UI_PREFAB_', p.scenes.filter((s) => s.prefab).map((s) => s.id)],
    ['UI_PATTERN_', p.gameplay?.patterns?.map((v) => v.id) ?? []],
    ['UI_ITEM_', p.gameplay?.rpg?.items.map((v) => v.id) ?? []],
    ['UI_SKILL_', p.gameplay?.rpg?.skills.map((v) => v.id) ?? []],
    ['UI_ACTOR_', p.gameplay?.rpg?.actors.map((v) => v.id) ?? []],
    ['UI_ENCOUNTER_', p.gameplay?.rpg?.encounters.map((v) => v.id) ?? []],
    ['UI_STATE_', p.gameplay?.state.map((v) => v.id) ?? []],
    ['UI_SCRIPT_', p.gameplay?.scripts.map((v) => v.id) ?? []],
    ['UI_NODE_', p.scenes.flatMap((s) => resolveScene(p, s).map((n) => n.id))],
    ['UI_SOUND_', p.audio.map((a) => a.id)],
    ['UI_SEQUENCE_', getFlow(p).sequences.map((s) => s.id)],
    ['UI_STEP_', getFlow(p).sequences.flatMap((s) => s.steps.map((step) => step.id))],
  ];
  const definitions = groups
    .map(([prefix, ids]) =>
      [...new Set(ids)]
        .sort()
        .map((id) => define(prefix, id))
        .filter(Boolean)
        .join('\n'),
    )
    .join('\n');
  return `/* Stable IDs: renaming display names does not change these. */\n#ifndef LVGL_GAME_UI_IDS_H\n#define LVGL_GAME_UI_IDS_H\n${definitions}\n#endif\n`;
}
