import type { InputConfig } from '../model';
import { hardwareInputIssues, hardwareSignature } from './model';
import { dkPin, pinLabel, dkPinoutSource } from './pins';
export function hardwareFiles(config?: InputConfig): Record<string, string> {
  const h = config?.hardware;
  if (!h) return {};
  const errors = hardwareInputIssues(h, config.channels);
  if (errors.length) throw Error(errors.join('\n'));
  const adc = h.pins.filter((p) => p.kind === 'adc'),
    gpio = h.pins.filter((p) => p.kind === 'gpio');
  const row = (p: (typeof h.pins)[number]) => {
    const channel = config.channels.findIndex((c) => c.id === p.channel),
      pin = dkPin(p.pin)!;
    return `{.channel=${channel},.port=GPIO${p.pin[1]},.pin=GPIO_PIN_${p.pin.slice(2)},.adc=${p.kind === 'adc' ? pin.adc!.instance : 0},.adc_channel=${p.kind === 'adc' ? 'ADC_CHANNEL_' + pin.adc!.channel : '0'},.pull=GPIO_${p.pull === 'none' ? 'NOPULL' : p.pull === 'up' ? 'PULLUP' : 'PULLDOWN'},.active_low=${p.activeLow},.debounce_ms=${p.debounceMs}}`;
  };
  return {
    'ui/ports/hardware-inputs.json':
      JSON.stringify(
        {
          ...h,
          signature: hardwareSignature(h),
          pins: h.pins.map((p) => ({ ...p, label: pinLabel(p.pin) })),
          adcCount: adc.length,
          gpioCount: gpio.length,
          resources: ['TIM3', ...(adc.length ? ['ADC1/ADC2'] : [])],
          monitorBaud: 115200,
        },
        null,
        2,
      ) + '\n',
    'ui/ports/hardware_inputs_config.h': `/* Generated by the hardware input wizard. Edit the project, then re-export. */
#ifndef LGE_DK_HARDWARE_CONFIG_H
#define LGE_DK_HARDWARE_CONFIG_H
#define LGE_DK_SAMPLE_HZ ${h.sampleHz}
#define LGE_DK_HARDWARE_SIGNATURE "${hardwareSignature(h)}"
#define LGE_DK_ADC_COUNT ${adc.length}
#define LGE_DK_GPIO_COUNT ${gpio.length}
#include "hardware_inputs.h"
extern const lge_dk_pin_t lge_dk_adc_pins[${Math.max(1, adc.length)}];
extern const lge_dk_pin_t lge_dk_gpio_pins[${Math.max(1, gpio.length)}];
#endif
`,
    'ui/ports/hardware_inputs_config.c': `#include "hardware_inputs_config.h"
const lge_dk_pin_t lge_dk_adc_pins[${Math.max(1, adc.length)}]={${adc.map(row).join(',\n') || '{0}'}};
const lge_dk_pin_t lge_dk_gpio_pins[${Math.max(1, gpio.length)}]={${gpio.map(row).join(',\n') || '{0}'}};
`,
    'ui/ports/CONTROLLER_WIRING.md': `# DK controller wiring\n\n${h.pins.map((p) => `- **${config.channels.find((c) => c.id === p.channel)!.name}**: ${pinLabel(p.pin)} → UI_CHANNEL_${p.channel.toUpperCase()} (${p.kind === 'adc' ? '12-bit ADC, 0–4095' : `${p.activeLow ? 'active low' : 'active high'}, pull ${p.pull}, ${p.debounceMs}ms debounce`})`).join('\n')}\n\nJoystick power: CN12 pin 4 (+3V3), ground: CN12 pin 6 or 7. Analog outputs must remain between GND and 3V3. A pull-up button connects its selected pin to GND when pressed; a pull-down button connects to 3V3. B2 needs no external wire.\n\n${h.factoryA4Routing ? 'A4 routing confirmed: SB26 ON, SB27 OFF.\n\n' : ''}Hardware acquisition: ${h.sampleHz} Hz via TIM3. ADC interrupts publish coherent per-ADC sequences. GPIO buttons are debounced and taps latch in the input bank between game frames. No sample queue, DMA buffers, heap or storage writes. ADCs use the current kernel clock divided by 16; no PLL or memory/display clock changes.\n\nBuild & flash: enable Stream inputs over ST-LINK serial for calibration. Only update the external application; leave Install board bootloader unchecked. The wizard never programs a board. Firmware still needs an application update after changing pins, polarity or debounce; center/range/deadzone changes also need a rebuild to reach the MCU.\n\nIn the editor, open Inputs & controllers → Hardware wizard → Calibrate & test, connect STLINK-V3 at 115200, leave the stick at rest and capture center, then capture its full range for both axes. Press each button and check its binding. Monitor-only is the default; enable Drive game to test the desktop C runtime.\n\nReference: [ST UM3289 rev 4, tables 22/27](${dkPinoutSource}). A4 uses factory solder routing; A5, peripheral-shared and reserved pins are excluded. Additional shields/modules must not drive selected inputs.\n`,
  };
}
