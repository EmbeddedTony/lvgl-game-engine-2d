// Bundle the canonical C board sources for both browser and Node authoring.
// Node's test runner cannot import Vite's ?raw modules.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const files = {};
for (const name of [
  'checkpoint_journal.h',
  'checkpoint_journal.c',
  'checkpoint_flash.h',
  'checkpoint_flash.c',
  'CHECKPOINTS.md',
  'debug_mailbox.h',
  'debug_mailbox.c',
  'debug_swd.h',
  'debug_swd.c',
  'input_monitor.h',
  'input_monitor.c',
  'input_monitor_text.h',
  'input_monitor_text.c',
  'INPUT_MONITOR.md',
  'hardware_inputs.h',
  'hardware_inputs.c',
  'input_debounce.h',
  'input_debounce.c',
])
  files['ui/ports/' + name] = fs.readFileSync(path.join(root, 'ports/stm32h7s78', name), 'utf8');
for (const name of fs.readdirSync(path.join(root, 'ports/stm32h7s78/vendor/adc')).sort())
  files['ui/ports/vendor/adc/' + name] = fs.readFileSync(
    path.join(root, 'ports/stm32h7s78/vendor/adc', name),
    'utf8',
  );
const target = path.join(root, 'src/boards/checkpoint-sources.generated.ts');
const source =
  '// Generated by scripts/sync-board-sources.cjs. Edit ports/stm32h7s78 instead.\n' +
  'export const checkpointSources: Record<string, string> = ' +
  JSON.stringify(files, null, 2) +
  ';\n';
if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== source)
  fs.writeFileSync(target, source);
